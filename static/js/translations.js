function changeLanguage(lang) {
    // 1. Met à jour le texte du bouton avec les initiales
    const displayElement = document.getElementById('current-lang-display');
    if (displayElement) {
        displayElement.innerText = lang.toUpperCase();
    }
    
    // 2. Traduit le texte classique
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (i18n[lang] && i18n[lang][key]) {
            element.innerText = i18n[lang][key];
        }
    });

    // 3. Traduit les "placeholders" (texte fantôme dans les champs de saisie)
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (i18n[lang] && i18n[lang][key]) {
            element.placeholder = i18n[lang][key];
        }
    });

    // 4. Sauvegarde dans le navigateur
    localStorage.setItem('banqueme-lang', lang);
}

// Appliquer la langue au chargement de la page
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('banqueme-lang') || 'fr';
    changeLanguage(savedLang);
});